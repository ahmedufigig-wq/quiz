    private val topicRx: List<Pair<List<Regex>, String>> =
        topics.map { (ks, e) -> ks.map { rx(it) } to e }

    private val flagRx: List<Pair<Regex, String>> =
        flags.map { (k, e) -> rx(k) to e }

    fun emojiFor(question: String): String {
        val t = norm(question)
        val topic = topicRx.firstOrNull { (rs, _) -> rs.any { it.containsMatchIn(t) } }?.second
        val flag = flagRx.firstOrNull { (r, _) -> r.containsMatchIn(t) }?.second
        return when {
            topic != null && flag != null -> topic + flag
            topic != null -> topic
            flag != null -> flag
            else -> "💡"
        }
    }
